import { describe, expect, it } from "vitest";
import {
	CATALOG_PRODUCT_INPUT_DESCRIPTION_MAX_IMAGE_ITEMS,
	CATALOG_PRODUCT_INPUT_DESCRIPTION_MAX_TOTAL_RUNES,
	CATALOG_PRODUCT_INPUT_SKUS_MAX_ITEMS,
	CATALOG_PRODUCT_INPUT_TITLE_MAX_RUNES,
	CATALOG_TABLE_ROW_CELLS_MAX_RUNES,
} from "../src/limits.gen";

describe("商品內容上限", () => {
	it("整份描述的文字總量是 3000、圖片 20，單一儲存格另有 200", () => {
		expect(CATALOG_PRODUCT_INPUT_DESCRIPTION_MAX_TOTAL_RUNES).toBe(3000);
		expect(CATALOG_PRODUCT_INPUT_DESCRIPTION_MAX_IMAGE_ITEMS).toBe(20);
		expect(CATALOG_TABLE_ROW_CELLS_MAX_RUNES).toBe(200);
	});

	it("標題與 SKU 數的上限來自商品寫入訊息欄位上的 limits option", () => {
		expect(CATALOG_PRODUCT_INPUT_TITLE_MAX_RUNES).toBe(100);
		expect(CATALOG_PRODUCT_INPUT_SKUS_MAX_ITEMS).toBe(100);
	});
});
