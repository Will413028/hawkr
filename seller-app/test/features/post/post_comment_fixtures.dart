/// 貼文留言的測試資料。預設是店主讀到買家的可見頂層留言（可刪、可回覆、不可編輯）。
PostComment testComment({
  String id = '1',
  String postId = '42',
  String? parentId,
  CommentState state = CommentState.COMMENT_STATE_VISIBLE,
  String author = '測試留言者',
  String body = '留言內容',
  bool isMine = false,
  bool canDelete = true,
  bool canReply = true,
  bool canEdit = false,
  int replyCount = 0,
  int likeCount = 0,
  bool liked = false,
  String? etag,
}) => PostComment(
  id: id,
  postId: postId,
  parentId: parentId,
  state: state,
  authorName: author,
  body: body,
  createTime: DateTime.now().subtract(const Duration(minutes: 5)),
  likeCount: likeCount,
  replyCount: replyCount,
  viewerLiked: liked,
  isMine: isMine,
  viewerCanEdit: canEdit,
  viewerCanDelete: canDelete,
  viewerCanReply: canReply,
  etag: etag ?? 'etag-$id',
);

