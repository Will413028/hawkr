/// 語意圖示，底層是 Material Icons，尺寸與顏色繼承 [IconTheme]。
///
/// [selected] 為 true 時，有 filled 版本的圖示改畫 filled，其餘維持 outlined。
class HkIcon extends StatelessWidget {
  const HkIcon(
    this.name, {
    super.key,
    this.size,
    this.color,
    this.selected = false,
    this.semanticLabel,
  });

  final HkIconName name;
  final double? size;
  final Color? color;
  final bool selected;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {
    final theme = IconTheme.of(context);
    final icon = Icon(
      (selected ? _filledIcon(name) : null) ?? _outlinedIcon(name),
      size: size ?? theme.size ?? 24,
      color: color ?? theme.color ?? AppIconColors.defaultColor,
      semanticLabel: semanticLabel,
      textDirection: Directionality.maybeOf(context),
    );
    if (semanticLabel?.trim().isNotEmpty ?? false) return icon;
    return ExcludeSemantics(child: icon);
  }
}

