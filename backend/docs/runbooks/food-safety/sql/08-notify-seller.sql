-- Variables to fill:
--   :notif_id            — 新 log 的 TSID（admin 自填）
--   :source_report_id    — 觸發此通知的 report id（seller_violation_reports.id 或 food_safety_reports.id）；無來源填 NULL
--   :source_report_table — 'seller_violation_reports' / 'food_safety_reports' / NULL
--   :template_key        — 通知模板 key (varchar(50))，例：'violation.warning' / 'violation.suspended' / 'violation.revoked' / 'appeal.accepted' / 'appeal.rejected'
--   :seller_id           — 收通知的賣家 id
--   :admin_id            — 觸發通知的 admin id（系統自動發則填 NULL）
--   :payload_json        — message_payload (jsonb)，例：'{"violation_id":12345,"reason":"food_safety","expires_at":"2026-05-14T00:00:00Z"}'
-- Audit: 執行後將完整 SQL + 結果貼到 Discord #food-safety-actions channel 留紀錄
-- Generated by B-169 (issue #722) — 2026-05-07
--
-- 重要：此 SQL 只寫 audit log，**不會** 真的把通知 push 到賣家！
--   完整流程需另外把訊息 publish 到 RabbitMQ 讓 notification-service 消費。
--   SQL 無法做 RabbitMQ publish。請依下列任一方式補發：
--     (a) admin UI 恢復後重跑該動作（系統會重發；本 log 用以查重）
--     (b) ops 用 rabbitmqctl / RabbitMQ Management UI 手動 publish 到對應 exchange
--     (c) 通知 notification-service owner 手動觸發
--   SQL fallback 場景下，本檔的價值在於：保留 admin 何時、以何模板、要通知誰的軌跡，
--   方便事後對帳避免漏發或重發。

BEGIN;

INSERT INTO seller_notification_log (
    id,
    source_report_id,
    source_report_table,
    template_key,
    seller_id,
    sent_by_admin_id,
    sent_at,
    message_payload
) VALUES (
    :notif_id,
    :source_report_id,           -- NULL 可
    :'source_report_table',      -- NULL 可（''：cast 失敗則改寫 NULL）
    :'template_key',
    :seller_id,
    :admin_id,                   -- NULL 可
    now(),
    :'payload_json'::jsonb
)
RETURNING id, seller_id, template_key, source_report_table, source_report_id, sent_by_admin_id, sent_at;

-- 驗證：撈該賣家近 24h 的通知 log，確認本筆已寫入且無重複模板
SELECT
    id,
    template_key,
    source_report_table,
    source_report_id,
    seller_id,
    sent_by_admin_id,
    sent_at,
    message_payload
FROM seller_notification_log
WHERE seller_id = :seller_id
  AND sent_at >= now() - interval '24 hours'
ORDER BY sent_at DESC
LIMIT 20;

-- 確認本筆 log 無誤（template_key / payload 正確）後 COMMIT
ROLLBACK; -- 確認後改 COMMIT;

