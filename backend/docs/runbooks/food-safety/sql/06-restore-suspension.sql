-- File: 06-restore-suspension.sql
-- Purpose: 解除賣家停權，把 sellers.status 從 'suspended_governance' 改回 'active'
-- When to use:
--   (a) admin 提前解除停權（e.g. 上訴成功 / 重新評估）
--   (b) cron worker 故障未自動跑：expires_at 已過但 sellers.status 還停在 suspended_governance，admin 手動還原
--   兩種情境共用此檔，差別只在要不要把 violation 標 revoked
-- Variables to fill:
--   :seller_id     — 賣家 id（sellers.account_id）
--   :violation_id  — 對應 violation.id；若情境 (b) 純粹是 cron 卡住、不需 revoke violation，填 NULL
--   :revoked_reason— revoked 原因 (varchar(50))，例：'admin_early_release' / 'appeal_accepted'；情境 (b) 不 revoke 時忽略
-- Audit: 執行後將完整 SQL + 結果貼到 Discord #food-safety-actions channel 留紀錄
-- Generated by B-169 (issue #722) — 2026-05-07
--
-- 兩種情境差異：
--   (a) 提前解除：要把 violation status='revoked'、revoked_at=now()、revoked_reason 填值
--   (b) 過期還原（cron 卡住）：violation 維持 enforced（已過 expires_at 自然失效）；
--       只還原 sellers.status 即可。此時 :violation_id 填 NULL 跳過 revoke 段。

BEGIN;

-- 1. （情境 a）revoke violation：僅當 :violation_id IS NOT NULL 才執行
--    若 :violation_id 為 NULL 則 WHERE 不會命中任何列，安全 no-op
UPDATE seller_violations
SET
    status = 'revoked',
    revoked_at = now(),
    revoked_reason = :'revoked_reason',
    updated_at = now()
WHERE id = :violation_id
  AND status = 'enforced'
  AND revoked_at IS NULL
RETURNING id, seller_id, penalty_type, status, revoked_at, revoked_reason, expires_at;

-- 2. 還原賣家狀態
--    只在當前 status='suspended_governance' 才改回 active（不覆蓋 deleted / 其他狀態）
UPDATE sellers
SET
    status = 'active',
    updated_at = now()
WHERE account_id = :seller_id
  AND status = 'suspended_governance'
RETURNING account_id, status, updated_at;

-- 3. 驗證：賣家當前狀態 + 該賣家所有未 revoke 的 enforced violations
SELECT
    s.account_id   AS seller_id,
    s.status       AS seller_status,
    s.updated_at   AS seller_updated_at,
    (
        SELECT COUNT(*)
        FROM seller_violations sv
        WHERE sv.seller_id = s.account_id
          AND sv.status = 'enforced'
          AND sv.revoked_at IS NULL
          AND sv.penalty_type IN ('full_suspension', 'partial_suspension')
          AND (sv.expires_at IS NULL OR sv.expires_at > now())
    ) AS active_suspension_count
FROM sellers s
WHERE s.account_id = :seller_id;

-- 預期：seller_status='active'、active_suspension_count=0；不符請 ROLLBACK 排查
ROLLBACK; -- 確認後改 COMMIT;
