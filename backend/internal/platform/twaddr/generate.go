//go:build ignore

// generate 由 moi-towns.csv 與 postal-codes.csv 產生三份只含資料的表（縣市與鄉鎮市區，已依郵遞區號排序）：
// towns_gen.go、packages/hawkr-twaddr-ts/src/twaddr.gen.ts、packages/hawkr_twaddr/lib/src/twaddr_data.g.dart。
// 查詢與組字串的邏輯在各平台手寫的檔案裡（twaddr.go、packages/hawkr-twaddr-ts/src/lookup.ts、packages/hawkr_twaddr/lib/hawkr_twaddr.dart）。
// 在本目錄執行 `go run generate.go`。
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"unicode/utf8"
)

func findRepoRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		panic(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "website")); err == nil {
			if _, err := os.Stat(filepath.Join(dir, "backend")); err == nil {
				return dir
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			panic("找不到 repo 根目錄")
		}
		dir = parent
	}
}

func read(path string) [][]string {
	f, err := os.Open(path)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	rows, err := csv.NewReader(f).ReadAll()
	if err != nil {
		panic(err)
	}
	return rows[1:]
}

type townRecord struct {
	code       string
	name       string
	countyCode string
	countyName string
	postalCode string
}

type countyRecord struct {
	code string
	name string
}

func main() {
	root := findRepoRoot()
	twaddrDir := filepath.Join(root, "backend", "internal", "platform", "twaddr")

	postal := map[string]string{}
	for _, r := range read(filepath.Join(twaddrDir, "postal-codes.csv")) {
		postal[r[0]] = r[1]
	}

	var records []townRecord
	var counties []countyRecord
	seenCounties := map[string]bool{}

	for _, r := range read(filepath.Join(twaddrDir, "moi-towns.csv")) {
		code, ok := postal[r[2]]
		if !ok {
			panic("沒有郵遞區號：" + r[2])
		}
		rec := townRecord{
			code:       r[2],
			name:       r[3],
			countyCode: r[0],
			countyName: r[1],
			postalCode: code,
		}
		records = append(records, rec)
		if !seenCounties[rec.countyCode] {
			seenCounties[rec.countyCode] = true
			counties = append(counties, countyRecord{code: rec.countyCode, name: rec.countyName})
		}
	}

	// 排序：鄉鎮市區依郵遞區號（同號依代碼），縣市依其鄉鎮市區中最小的郵遞區號先後出現。
	// 下拉選單照這個順序顯示；縣市由排序後的鄉鎮市區首次出現的順序得出。
	sort.SliceStable(records, func(i, j int) bool {
		if records[i].postalCode != records[j].postalCode {
			return records[i].postalCode < records[j].postalCode
		}
		return records[i].code < records[j].code
	})
	counties = counties[:0]
	seenCounties = map[string]bool{}
	for _, rec := range records {
		if !seenCounties[rec.countyCode] {
			seenCounties[rec.countyCode] = true
			counties = append(counties, countyRecord{code: rec.countyCode, name: rec.countyName})
		}
	}

	// 1. Go: towns_gen.go
	var goBuf bytes.Buffer
	goBuf.WriteString("// Code generated by generate.go from moi-towns.csv and postal-codes.csv. DO NOT EDIT.\n\npackage twaddr\n\nvar towns = []Town{\n")
	for _, r := range records {
		fmt.Fprintf(&goBuf, "\t{Code: %q, Name: %q, CountyCode: %q, CountyName: %q, PostalCode: %q},\n", r.code, r.name, r.countyCode, r.countyName, r.postalCode)
	}
	goBuf.WriteString("}\n")
	src, err := format.Source(goBuf.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(twaddrDir, "towns_gen.go"), src, 0o644); err != nil {
		panic(err)
	}

	const header = "Code generated by backend/internal/platform/twaddr/generate.go from moi-towns.csv and postal-codes.csv. DO NOT EDIT."

	// 2. TypeScript: packages/hawkr-twaddr-ts/src/twaddr.gen.ts（只有資料；型別與查詢在手寫的 lookup.ts）
	var tsBuf bytes.Buffer
	fmt.Fprintf(&tsBuf, "// %s\n\n", header)
	tsBuf.WriteString("export const COUNTIES = [\n")
	for _, c := range counties {
		fmt.Fprintf(&tsBuf, "\t{ code: %q, name: %q },\n", c.code, c.name)
	}
	tsBuf.WriteString("] as const;\n\nexport const TOWNS = [\n")
	for _, r := range records {
		fmt.Fprintf(&tsBuf, "\t{ code: %q, name: %q, countyCode: %q, postalCode: %q },\n", r.code, r.name, r.countyCode, r.postalCode)
	}
	tsBuf.WriteString("] as const;\n")
	tsPath := filepath.Join(root, "packages", "hawkr-twaddr-ts", "src", "twaddr.gen.ts")
	if err := os.WriteFile(tsPath, tsBuf.Bytes(), 0o644); err != nil {
		panic(err)
	}

	// 3. Dart: packages/hawkr_twaddr/lib/src/twaddr_data.g.dart（只有資料；類別與查詢是手寫的）
	// 輸出與 dart format 一致（參數過長時逐行展開、帶結尾逗號），packages 的 format 檢查才不會和生成物打架。
	var dartBuf bytes.Buffer
	fmt.Fprintf(&dartBuf, "// %s\n\nimport 'town.dart';\n\nconst List<County> counties = [\n", header)
	for _, c := range counties {
		fmt.Fprintf(&dartBuf, "  County(code: %q, name: %q),\n", c.code, c.name)
	}
	dartBuf.WriteString("];\n\nconst List<Town> towns = [\n")
	for _, r := range records {
		line := fmt.Sprintf("  Town(code: %q, name: %q, countyCode: %q, postalCode: %q),\n", r.code, r.name, r.countyCode, r.postalCode)
		if utf8.RuneCountInString(line) > 81 { // 80 欄加換行
			line = fmt.Sprintf("  Town(\n    code: %q,\n    name: %q,\n    countyCode: %q,\n    postalCode: %q,\n  ),\n", r.code, r.name, r.countyCode, r.postalCode)
		}
		dartBuf.WriteString(line)
	}
	dartBuf.WriteString("];\n")
	dartPath := filepath.Join(root, "packages", "hawkr_twaddr", "lib", "src", "twaddr_data.g.dart")
	if err := os.MkdirAll(filepath.Dir(dartPath), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(dartPath, dartBuf.Bytes(), 0o644); err != nil {
		panic(err)
	}
}
