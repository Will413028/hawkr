// 從 src/presets.ts 生成各 client 的 preset 名稱（ADR backend/docs/adr/2026-09-25-api-image-uri-template.md D4）：
// presets.ts 是唯一來源，client 不手寫清單。CI（api-contract.yml）重新生成並檢查 drift。
//
// 在 repo 任何位置執行：node backend/workers/image-gateway/scripts/gen-client-presets.mjs
// presets.ts 只用可擦除的 TypeScript 語法，Node 直接 import（type stripping，Node 22.18 以上）。
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { ORIGINAL_PRESET_NAME, PRESETS } from "../src/presets.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../../..");
const names = [...Object.keys(PRESETS), ORIGINAL_PRESET_NAME];
for (const n of names) {
	// ADR D3：client 以字串替換 {preset}，名稱必須是 RFC 6570 的 unreserved 字元。
	if (!/^[a-z]+$/.test(n)) {
		throw new Error(`preset 名稱 ${n} 不是小寫字母`);
	}
}

const header =
	"Code generated by backend/workers/image-gateway/scripts/gen-client-presets.mjs from src/presets.ts. DO NOT EDIT.";
const doc = "圖片 preset 的名稱：image gateway 的白名單（ADR 2026-09-25-api-image-uri-template D4）。";

const ts = `// ${header}

/** ${doc} */
export const IMAGE_PRESETS = [
${names.map((n) => `\t"${n}",`).join("\n")}
] as const;

export type ImagePreset = (typeof IMAGE_PRESETS)[number];
`;

const dart = `// ${header}

// dart format off

/// ${doc}
enum ImagePreset {
${names.map((n) => `  ${n},`).join("\n")}
}
`;

const outputs = {
	"website/lib/media/image-presets.generated.ts": ts,
	"admin/src/utils/image-presets.generated.ts": ts,
	"packages/hawkr_api/lib/image_presets.g.dart": dart,
};
for (const [path, content] of Object.entries(outputs)) {
	writeFileSync(join(root, path), content);
	console.log(`✓ ${path}`);
}
