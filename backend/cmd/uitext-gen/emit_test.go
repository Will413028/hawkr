func outputs(t *testing.T, mutate func(*Inputs)) (*Model, map[string][]byte) {
	t.Helper()
	m := mustBuild(t, mutate)
	out, err := m.Outputs()
	if err != nil {
		t.Fatalf("Outputs 失敗：%v", err)
	}
	return m, out
}

func TestOutputsAreDeterministic(t *testing.T) {
	_, a := outputs(t, nil)
	_, b := outputs(t, nil)
	if len(a) != len(b) {
		t.Fatalf("輸出數量不同：%d vs %d", len(a), len(b))
	}
	for p, content := range a {
		if string(b[p]) != string(content) {
			t.Errorf("%s 兩次輸出不同", p)
		}
	}
}

