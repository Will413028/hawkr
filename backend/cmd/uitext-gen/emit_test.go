func TestMessagesAreMergedAndExcludeStaff(t *testing.T) {
	_, out := outputs(t, nil)
	var zh, en map[string]any
	if err := json.Unmarshal(out["packages/hawkr-ui-text-ts/src/messages/zh-TW.gen.json"], &zh); err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(out["packages/hawkr-ui-text-ts/src/messages/en.gen.json"], &en); err != nil {
		t.Fatal(err)
	}
	get := func(m map[string]any, path ...string) any {
		var cur any = m
		for _, p := range path {
			next, ok := cur.(map[string]any)
			if !ok {
				return nil
			}
			cur = next[p]
		}
		return cur
	}
	if get(zh, "fx", "Color", "COLOR_RED") != "紅" || get(en, "fx", "Color", "COLOR_RED") != "Red" {
		t.Error("RED：zh 紅、en Red")
	}
	// en 缺字填 zh-TW 的文字。
	if get(en, "fx", "Color", "COLOR_BLUE") != "藍" {
		t.Errorf("en 缺字要填 zh-TW：%v", get(en, "fx", "Color", "COLOR_BLUE"))
	}
	// staff 不在 messages；omit 的值不在 messages。
	if get(zh, "fx", "Mode", "MODE_B") != "模式乙" {
		t.Errorf("messages 是預設受眾：%v", get(zh, "fx", "Mode", "MODE_B"))
	}
	if get(zh, "fx", "Color", "label", "COLOR_GREEN") != nil {
		t.Error("omit 的值不在 messages")
	}
	// 巢狀 enum。
	if get(zh, "fx", "Box", "Size", "SIZE_SMALL") != "小" {
		t.Error("巢狀 enum 的 key 要是巢狀物件")
	}
}

func TestManifest(t *testing.T) {
	_, out := outputs(t, nil)
	type entry struct {
		Name        string `json:"name"`
		TSName      string `json:"tsName"`
		TSModule    string `json:"tsModule"`
		DartClass   string `json:"dartClass"`
		InCatalog   bool   `json:"inCatalog"`
		ServerOwned bool   `json:"serverOwned"`
	}
	load := func(p string) map[string]entry {
		var m struct{ Enums []entry }
		if err := json.Unmarshal(out[p], &m); err != nil {
			t.Fatal(err)
		}
		res := map[string]entry{}
		for _, e := range m.Enums {
			res[e.Name] = e
		}
		return res
	}
	ts := load("packages/hawkr-ui-text-ts/src/enum-manifest.gen.json")
	dart := load("packages/hawkr_ui_text/tool/enum_manifest.g.json")
	if e := ts["hawkr.fx.v1alpha1.Box.Size"]; e.TSName != "Box_Size" || e.TSModule != "@hawkr/api/gen/hawkr/fx/v1alpha1/fx_pb" || !e.InCatalog {
		t.Errorf("巢狀 enum 的 TS 名稱：%+v", e)
	}
	if !ts["hawkr.common.v1alpha1.ErrorReason"].ServerOwned || !ts["hawkr.fx.v1alpha1.GadgetUnavailableReason"].ServerOwned {
		t.Error("ErrorReason 與 *Unavailability.reason 的 enum 是伺服器擁有的")
	}
	if ts["hawkr.fx.v1alpha1.Tone"].InCatalog {
		t.Error("Tone 不在目錄")
	}
	if _, ok := ts["hawkr.admin.fx.v1alpha1.Level"]; !ok {
		t.Error("TS manifest 含 admin")
	}
	if _, ok := dart["hawkr.admin.fx.v1alpha1.Level"]; ok {
		t.Error("Dart manifest 不含 hawkr.admin.*")
	}
	if e := dart["hawkr.fx.v1alpha1.Box.Size"]; e.DartClass != "Box_Size" {
		t.Errorf("Dart 類別名稱：%+v", e)
	}
}

func goldenOf(t *testing.T, out map[string][]byte) []GoldenCase {
	t.Helper()
	var cases []GoldenCase
	if err := json.Unmarshal(out["backend/internal/platform/uitext/testdata/golden.gen.json"], &cases); err != nil {
		t.Fatal(err)
	}
	return cases
}

func findGolden(cases []GoldenCase, key, aud, loc string, params map[string]any) *GoldenCase {
	for i, c := range cases {
		if c.Key != key || string(c.Audience) != aud || c.Locale != loc {
			continue
		}
		match := true
		for k, v := range params {
			if c.Params[k] != v {
				match = false
			}
		}
		if match {
			return &cases[i]
		}
	}
	return nil
}

func TestGolden(t *testing.T) {
	_, out := outputs(t, func(in *Inputs) {
		in.Catalog["en"].Default["fx.Note.count"] = Entry{Message: "{n, plural, one {{n} item} other {{n} items}}"}
	})
	cases := goldenOf(t, out)
	want := func(key, aud, loc string, params map[string]any, text string, isNil bool) {
		t.Helper()
		c := findGolden(cases, key, aud, loc, params)
		if c == nil {
			t.Errorf("golden 缺 %s [%s %s] %v", key, aud, loc, params)
			return
		}
		if isNil {
			if c.Want != nil {
				t.Errorf("%s [%s %s] %v 應該沒有文字，得到 %q", key, aud, loc, params, *c.Want)
			}
			return
		}
		if c.Want == nil || *c.Want != text {
			t.Errorf("%s [%s %s] %v：got %v want %q", key, aud, loc, params, c.Want, text)
		}
	}
	// 名詞、en 缺字、en 有翻譯。
	want("fx.Color.COLOR_RED", "default", "zh-TW", nil, "紅", false)
	want("fx.Color.COLOR_RED", "default", "en", nil, "Red", false)
	want("fx.Color.COLOR_BLUE", "default", "en", nil, "藍", false)
	// select：分支與 other（UNSPECIFIED）；staff 受眾；
	want("fx.Mode.MODE_A", "default", "zh-TW", map[string]any{"color": "COLOR_RED"}, "紅色模式", false)
	want("fx.Mode.MODE_A", "default", "zh-TW", map[string]any{"color": "COLOR_UNSPECIFIED"}, "模式甲", false)
	want("fx.Mode.MODE_A", "staff", "zh-TW", map[string]any{"color": "COLOR_RED"}, "後台紅", false)
	// 名詞參數：同語系；不認得整個沒有文字；
	want("fx.Box.title", "default", "zh-TW", map[string]any{"color": "COLOR_RED"}, "盒子：紅", false)
	want("fx.Box.title", "default", "zh-TW", map[string]any{"color": "COLOR_UNSPECIFIED"}, "", true)
	// 變體：omit 的值沒有文字。
	want("fx.Color.label.COLOR_RED", "default", "zh-TW", map[string]any{"n": "示例"}, "顏色：示例", false)
	if c := findGolden(cases, "fx.Color.label.COLOR_GREEN", "default", "zh-TW", nil); c != nil {
		t.Error("omit 的值沒有 key，不應該有 golden 的 key 列（以 omit 檢查另列）")
	}
	// plural：zh 只有 other；en 有 one。整數不分組。
	want("fx.Note.count", "default", "zh-TW", map[string]any{"n": float64(1)}, "共 1 筆", false)
	want("fx.Note.count", "default", "zh-TW", map[string]any{"n": float64(1234)}, "共 1234 筆", false)
	want("fx.Note.count", "default", "en", map[string]any{"n": float64(1)}, "1 item", false)
	want("fx.Note.count", "default", "en", map[string]any{"n": float64(2)}, "2 items", false)
	want("fx.Note.count", "default", "en", map[string]any{"n": float64(1234)}, "1234 items", false)
	// en 的 plural 有 one 分支：Go 與 Dart 的 emitter 要生成呼叫複數規則的程式碼。
	if src := string(out["backend/internal/platform/uitext/catalog_gen.go"]); !strings.Contains(src, "PluralCategory(EN, n)") {
		t.Error("Go：en 的 plural 要呼叫 PluralCategory")
	}
	if src := string(out["packages/hawkr_ui_text/lib/src/ui_text.g.dart"]); !strings.Contains(src, "Intl.pluralLogic(n, one: ") {
		t.Error("Dart：en 的 plural 要呼叫 Intl.pluralLogic")
	}
	_ = cases
}

// 名詞對 UNSPECIFIED 與不認得的值三端一致地「沒有文字」（Go 的 (string, bool)、TS 的 undefined、Dart 的 null），
// 「未知」由呼叫端明確用 common.unknown 的存取函式；生成碼不替呼叫端補「未知」。
func TestNounsHaveNoTextForUnknownValuesInEveryRuntime(t *testing.T) {
	_, out := outputs(t, nil)
	ts := string(out["packages/hawkr-ui-text-ts/src/keys.gen.ts"])
	for _, want := range []string{
		"export function fxColor(v: Color): UiMessage | undefined {",
		"export function commonUnknown(): UiMessage {",
	} {
		if !strings.Contains(ts, want) {
			t.Errorf("keys.gen.ts 缺 %q", want)
		}
	}
	if strings.Count(ts, `return { key: "common.unknown" }`) != 1 {
		t.Errorf("common.unknown 只能由 commonUnknown() 回，實際出現 %d 次", strings.Count(ts, `return { key: "common.unknown" }`))
	}
	dart := string(out["packages/hawkr_ui_text/lib/src/ui_text.g.dart"])
	if !strings.Contains(dart, "String? uiText(UiLocale l) =>") || strings.Contains(dart, "?? commonUnknown(l)") {
		t.Error("Dart 的名詞要回 String?，不在生成碼裡補 commonUnknown")
	}
	goSrc := string(out["backend/internal/platform/uitext/catalog_gen.go"])
	if !strings.Contains(goSrc, "func (t Text) FxColor(v string) (string, bool)") {
		t.Error("Go 的名詞回 (string, bool)")
	}
}
