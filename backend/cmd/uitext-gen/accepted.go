// acceptedOption 是欄位選項 hawkr.common.v1alpha1.accepted_policy_categories 的全名（api/hawkr/common/v1alpha1/accepted_values.proto）。
const acceptedOption protoreflect.FullName = "hawkr.common.v1alpha1.accepted_policy_categories"

// AcceptedField 是一個掛了 accepted_policy_categories 的請求欄位：欄位接受的列舉值，依 proto 的宣告順序，不含零值。
type AcceptedField struct {
	// Path 是 key 風格的路徑：短 package、訊息與欄位，例如 seller.CreateReportRequest.category。
	Path   string
	Enum   *EnumInfo
	Values []protoreflect.EnumValueDescriptor
}

// AcceptedFields 讀出 image 裡所有掛了 accepted_policy_categories 的欄位，依 Path 排序。
// 擴充欄位在這支程式裡沒有編譯進來的型別，所以用 image 自己的描述建 resolver 重新解碼欄位選項；
// 沒有解碼的話 protodesc 保留的選項只有 unknown fields，讀不到值。
func (s *Schema) AcceptedFields() ([]*AcceptedField, error) {
	d, err := s.files.FindDescriptorByName(acceptedOption)
	if err != nil {
		// image 沒有這個 option 的定義，也就沒有任何欄位用它。
		return nil, nil //nolint:nilerr // 沒有定義就沒有用到
	}
	xd, ok := d.(protoreflect.ExtensionDescriptor)
	if !ok || !xd.IsList() || xd.Enum() == nil || xd.Enum().FullName() != "hawkr.common.v1alpha1.PolicyCategory" {
		return nil, fmt.Errorf("%s 必須是 repeated PolicyCategory 的 FieldOptions 擴充欄位", acceptedOption)
	}
	xt := dynamicpb.NewExtensionType(xd)
	resolver := &protoregistry.Types{}
	if err := resolver.RegisterExtension(xt); err != nil {
		return nil, err
	}
	var out []*AcceptedField
	var errs errList
	var walk func(fd protoreflect.FileDescriptor, ms protoreflect.MessageDescriptors)
	walk = func(fd protoreflect.FileDescriptor, ms protoreflect.MessageDescriptors) {
		for i := range ms.Len() {
			m := ms.Get(i)
			fs := m.Fields()
			for j := range fs.Len() {
				f := fs.Get(j)
				raw, ok := f.Options().(*descriptorpb.FieldOptions)
				if !ok || raw == nil {
					continue
				}
				b, err := proto.Marshal(raw)
				if err != nil {
					errs.addf("%s：%v", f.FullName(), err)
					continue
				}
				var opts descriptorpb.FieldOptions
				if err := (proto.UnmarshalOptions{Resolver: resolver}).Unmarshal(b, &opts); err != nil {
					errs.addf("%s：%v", f.FullName(), err)
					continue
				}
				if !opts.ProtoReflect().Has(xt.TypeDescriptor()) {
					continue
				}
				af := s.acceptedField(f, opts.ProtoReflect().Get(xt.TypeDescriptor()).List(), &errs)
				if af != nil {
					out = append(out, af)
				}
			}
			walk(fd, m.Messages())
		}
	}
	s.files.RangeFiles(func(fd protoreflect.FileDescriptor) bool {
		if _, ok := s.pkgShort[string(fd.Package())]; ok {
			walk(fd, fd.Messages())
		}
		return true
	})
	if err := errs.err(); err != nil {
		return nil, err
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

func (s *Schema) acceptedField(f protoreflect.FieldDescriptor, list protoreflect.List, errs *errList) *AcceptedField {
	pkg := string(f.ParentFile().Package())
	path := s.pkgShort[pkg] + "." + strings.TrimPrefix(string(f.FullName()), pkg+".")
	enum, ok := s.enumByName("hawkr.common.v1alpha1.PolicyCategory")
	if !ok {
		errs.addf("%s：image 沒有 PolicyCategory", f.FullName())
		return nil
	}
	if f.Enum() == nil || f.Enum().FullName() != enum.Desc.FullName() || f.IsList() {
		errs.addf("%s：%s 只能掛在單值的 PolicyCategory 欄位", f.FullName(), acceptedOption)
		return nil
	}
	af := &AcceptedField{Path: path, Enum: enum}
	seen := map[protoreflect.EnumNumber]bool{}
	for i := range list.Len() {
		n := protoreflect.EnumNumber(list.Get(i).Enum())
		v := enum.Desc.Values().ByNumber(n)
		switch {
		case n == 0:
			errs.addf("%s：%s 不得含 UNSPECIFIED", f.FullName(), acceptedOption)
		case v == nil:
			errs.addf("%s：%s 有不認得的值號 %d", f.FullName(), acceptedOption, n)
		case seen[n]:
			errs.addf("%s：%s 重複列出 %s", f.FullName(), acceptedOption, v.Name())
		default:
			af.Values = append(af.Values, v)
		}
		seen[n] = true
	}
	if len(af.Values) == 0 {
		errs.addf("%s：%s 是空的", f.FullName(), acceptedOption)
	}
	return af
}

// goCategory 是值名去掉 POLICY_CATEGORY_ 前綴後的儲存代碼（platform/policy.Category 的值）。
func (a *AcceptedField) goCategory(v protoreflect.EnumValueDescriptor) string {
	return strings.TrimPrefix(string(v.Name()), a.Enum.Prefix)
}

// EmitGoAccepted 生成 platform/policy 的清單：Category 是字串型別，值是儲存代碼。
func EmitGoAccepted(fields []*AcceptedField) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by backend/cmd/uitext-gen; DO NOT EDIT.\n// " + generatedHeader + "\n\npackage policy\n")
	for _, a := range fields {
		fmt.Fprintf(&b, "\n// accepted%s 是 %s 接受的類別（%s），順序同 proto。\nvar accepted%s = []Category{\n", pascal(a.Path), a.Path, acceptedOption, pascal(a.Path))
		for _, v := range a.Values {
			fmt.Fprintf(&b, "\tCategory(%q),\n", a.goCategory(v))
		}
		b.WriteString("}\n")
	}
	return format.Source([]byte(b.String()))
}

// EmitTSAccepted 生成 @hawkr/ui-text 的 accepted.gen.ts：值是 @hawkr/api 的 PolicyCategory 成員。
func EmitTSAccepted(fields []*AcceptedField) []byte {
	var b strings.Builder
	b.WriteString(tsHeader)
	if len(fields) > 0 {
		fmt.Fprintf(&b, "import { PolicyCategory } from %s;\n", jsString(tsModule(fields[0].Enum)))
	}
	for _, a := range fields {
		fmt.Fprintf(&b, "\n/** %s 接受的類別（%s），順序同 proto。 */\nexport const %s: readonly PolicyCategory[] = [\n", a.Path, acceptedOption, constName(a.Path))
		for _, v := range a.Values {
			fmt.Fprintf(&b, "\tPolicyCategory.%s,\n", strings.TrimPrefix(string(v.Name()), a.Enum.Prefix))
		}
		b.WriteString("];\n")
	}
	return []byte(b.String())
}

// EmitDartAccepted 生成 hawkr_ui_text 的 accepted.g.dart：值是 hawkr_api 的 PolicyCategory 成員。
func EmitDartAccepted(fields []*AcceptedField) []byte {
	var b strings.Builder
	b.WriteString("// dart format off\n// 由 backend/cmd/uitext-gen 生成，不得手改；重新生成：在 backend 目錄執行 make uitext。\n\n")
	b.WriteString("// ignore_for_file: unused_import, prefer_single_quotes\n")
	if len(fields) > 0 {
		e := fields[0].Enum
		fmt.Fprintf(&b, "\nimport '%s' as %s;\n", dartLibrary(e), dartAlias(e))
	}
	for _, a := range fields {
		g := &dartGen{}
		fmt.Fprintf(&b, "\n/// %s 接受的類別（%s），順序同 proto。\nconst List<%s> %s = <%s>[\n", a.Path, acceptedOption, g.typeName(a.Enum), lowerFirst(pascal(a.Path)), g.typeName(a.Enum))
		for _, v := range a.Values {
			fmt.Fprintf(&b, "  %s.%s,\n", g.typeName(a.Enum), v.Name())
		}
		b.WriteString("];\n")
	}
	return []byte(b.String())
}
