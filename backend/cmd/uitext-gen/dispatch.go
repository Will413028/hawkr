// 三個執行期的 golden 測試需要「依 fn 與 value 呼叫生成的 API」的分派表。它們和輸出一起生成（不是公開 API），
// 這樣每個生成的函式都被 golden 實際呼叫，不靠另一份手寫的呼叫表。

// EmitGoGoldenCalls 生成 golden_calls_gen_test.go（package uitext）。
func (m *Model) EmitGoGoldenCalls() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by backend/cmd/uitext-gen; DO NOT EDIT.\n// " + generatedHeader + "\n\npackage uitext\n\n")
	b.WriteString(`import "strings"

// goldenCase 是 testdata/golden.gen.json 的一筆。
type goldenCase struct {
	Key      string         ` + "`json:\"key\"`" + `
	Fn       string         ` + "`json:\"fn\"`" + `
	Value    string         ` + "`json:\"value\"`" + `
	Audience string         ` + "`json:\"audience\"`" + `
	Locale   string         ` + "`json:\"locale\"`" + `
	Params   map[string]any ` + "`json:\"params\"`" + `
	Want     *string        ` + "`json:\"want\"`" + `
}

func goldenString(c goldenCase, name string) string {
	s, _ := c.Params[name].(string)
	return s
}

func goldenInt(c goldenCase, name string) int {
	n, _ := c.Params[name].(float64)
	return int(n)
}

// goldenEnum 把 golden 的值名轉成模組的值：UNSPECIFIED 是空字串，其餘去掉前綴。
func goldenEnum(name, prefix string) string {
	if strings.HasSuffix(name, "UNSPECIFIED") {
		return ""
	}
	return strings.TrimPrefix(name, prefix)
}

// goldenCall 呼叫 c.Fn 對應的生成函式；ok 是 false 表示「沒有文字」。
func goldenCall(t Text, c goldenCase) (string, bool) {
	switch c.Fn {
`)
	for _, f := range m.Funcs {
		fmt.Fprintf(&b, "case %q:\n", f.ID)
		var args []string
		switch f.Kind { //nolint:exhaustive // 其餘種類走預設分支
		case FuncNoun, FuncVariant:
			args = append(args, fmt.Sprintf("goldenEnum(c.Value, %q)", f.Enum.Prefix))
		case FuncError:
			args = append(args, "c.Value")
		}
		for _, p := range f.Params {
			switch p.Kind { //nolint:exhaustive // 其餘種類走預設分支
			case ParamString:
				args = append(args, fmt.Sprintf("goldenString(c, %q)", p.Name))
			case ParamInteger:
				args = append(args, fmt.Sprintf("goldenInt(c, %q)", p.Name))
			default:
				args = append(args, fmt.Sprintf("goldenEnum(goldenString(c, %q), %q)", p.Name, p.Enum.Prefix))
			}
		}
		call := fmt.Sprintf("t.%s(%s)", pascal(f.ID), strings.Join(args, ", "))
		if f.Kind == FuncError {
			fmt.Fprintf(&b, "m, ok := %s\nreturn m.Text, ok\n", call)
		} else if goReturnsOK(f) {
			fmt.Fprintf(&b, "return %s\n", call)
		} else {
			fmt.Fprintf(&b, "return %s, true\n", call)
		}
	}
	b.WriteString("}\nreturn \"\", false\n}\n")
	return format.Source([]byte(b.String()))
}

func (m *Model) enumNumberTable(enums []*EnumInfo, quote func(string) string) string {
	var parts []string
	for _, e := range enums {
		for _, v := range enumNames(e) {
			parts = append(parts, fmt.Sprintf("%s: %d", quote(string(v.Name())), v.Number()))
		}
	}
	sort.Strings(parts)
	return strings.Join(parts, ",\n\t")
}

// EmitTSGoldenCalls 生成 tests/golden-calls.gen.ts。
func (m *Model) EmitTSGoldenCalls() []byte {
	enums := m.usedEnums()
	var b strings.Builder
	b.WriteString(tsHeader)
	b.WriteString("import { Code } from \"@connectrpc/connect\";\n")
	var names []string
	var stNames []string
	for _, f := range m.Funcs {
		names = append(names, lowerFirst(pascal(f.ID)))
		if f.Kind == FuncVariant && f.HasStaff {
			stNames = append(stNames, lowerFirst(pascal(f.ID))+"Staff")
		}
	}
	sort.Strings(names)
	sort.Strings(stNames)
	fmt.Fprintf(&b, "import { %s } from \"../src/keys.gen\";\n", strings.Join(names, ", "))
	if len(stNames) > 0 {
		fmt.Fprintf(&b, "import { %s } from \"../src/zh-tw.gen\";\n", strings.Join(stNames, ", "))
	}
	b.WriteString("import type { UiMessage } from \"../src/message\";\n\n")
	b.WriteString(`export interface GoldenCase {
	key: string;
	fn: string;
	value?: string;
	audience: "default" | "staff";
	locale: string;
	params?: Record<string, string | number>;
	want: string | null;
}

`)
	fmt.Fprintf(&b, "const ENUM_NUMBER: Readonly<Record<string, number>> = {\n\t%s,\n};\n\n", m.enumNumberTable(enums, jsString))
	b.WriteString("const CODES: Readonly<Record<string, Code>> = {\n")
	for _, c := range connectCodes {
		fmt.Fprintf(&b, "\t%s: Code.%s,\n", jsString(c), connectCodeName(c))
	}
	b.WriteString("};\n\n")
	b.WriteString(`function num(name: string | number | undefined): number {
	const n = typeof name === "string" ? ENUM_NUMBER[name] : undefined;
	if (n === undefined) throw new Error("unknown enum value " + String(name));
	return n;
}

/** 呼叫 c.fn 對應的生成函式；undefined 表示「沒有文字」。 */
export function goldenMessage(c: GoldenCase): UiMessage | undefined {
	const p = c.params ?? {};
	switch (c.fn) {
`)
	for _, f := range m.Funcs {
		fmt.Fprintf(&b, "\tcase %s: {\n", jsString(f.ID))
		call := func(name string) string {
			var args []string
			switch f.Kind { //nolint:exhaustive // 其餘種類走預設分支
			case FuncNoun, FuncVariant:
				args = append(args, "num(c.value)")
			case FuncError:
				args = append(args, "CODES[c.value ?? \"\"]")
			}
			if len(f.Params) > 0 {
				var fields []string
				for _, pr := range f.Params {
					switch pr.Kind { //nolint:exhaustive // 其餘種類走預設分支
					case ParamString:
						fields = append(fields, fmt.Sprintf("%s: p.%s as string", pr.Name, pr.Name))
					case ParamInteger:
						fields = append(fields, fmt.Sprintf("%s: p.%s as number", pr.Name, pr.Name))
					default:
						fields = append(fields, fmt.Sprintf("%s: num(p.%s)", pr.Name, pr.Name))
					}
				}
				args = append(args, "{ "+strings.Join(fields, ", ")+" }")
			}
			return fmt.Sprintf("%s(%s)", name, strings.Join(args, ", "))
		}
		base := lowerFirst(pascal(f.ID))
		if f.Kind == FuncVariant && f.HasStaff {
			fmt.Fprintf(&b, "\t\tif (c.audience === \"staff\") return %s;\n", call(base+"Staff"))
		}
		fmt.Fprintf(&b, "\t\treturn %s;\n\t}\n", call(base))
	}
	b.WriteString("\tdefault:\n\t\tthrow new Error(\"unknown golden fn \" + c.fn);\n\t}\n}\n")
	return []byte(b.String())
}

// EmitDartGoldenCalls 生成 test/golden_calls.g.dart。Dart 只有預設受眾。
func (m *Model) EmitDartGoldenCalls() []byte {
	enums := m.usedEnums()
	var b strings.Builder
	b.WriteString("// dart format off\n// " + generatedHeader + "\n\n")
	b.WriteString("// ignore_for_file: unnecessary_parenthesis, unused_import\n\n")
	b.WriteString("import 'package:connectrpc/connect.dart' show Code;\n")
	libs := map[string]*EnumInfo{}
	var libOrder []string
	for _, e := range enums {
		lib := dartLibrary(e)
		if _, ok := libs[lib]; !ok {
			libs[lib] = e
			libOrder = append(libOrder, lib)
		}
	}
	sort.Strings(libOrder)
	for _, lib := range libOrder {
		fmt.Fprintf(&b, "import '%s' as %s;\n", lib, dartAlias(libs[lib]))
	}
	b.WriteString("import 'package:hawkr_ui_text/hawkr_ui_text.dart';\n\n")
	fmt.Fprintf(&b, "const _enumNumber = <String, int>{\n  %s,\n};\n\n", m.enumNumberTable(enums, dartString))
	b.WriteString("const _codes = <String, Code>{\n")
	for _, c := range connectCodes {
		fmt.Fprintf(&b, "  '%s': Code.%s,\n", c, lowerFirst(connectCodeName(c)))
	}
	b.WriteString("};\n\n")
	b.WriteString(`int _n(Object? name) => _enumNumber[name]!;

/// 呼叫 fn 對應的生成函式；null 表示「沒有文字」。
String? goldenText(String fn, String value, Map<String, Object?> params, UiLocale l) {
  switch (fn) {
`)
	for _, f := range m.Funcs {
		fmt.Fprintf(&b, "    case %s:\n", dartString(f.ID))
		var named []string
		for _, p := range f.Params {
			switch p.Kind { //nolint:exhaustive // 其餘種類走預設分支
			case ParamString:
				named = append(named, fmt.Sprintf("%s: params['%s']! as String", p.Name, p.Name))
			case ParamInteger:
				named = append(named, fmt.Sprintf("%s: (params['%s']! as num).toInt()", p.Name, p.Name))
			default:
				named = append(named, fmt.Sprintf("%s: %s.%s.valueOf(_n(params['%s']))!", p.Name, dartAlias(p.Enum), enumTypeName(p.Enum), p.Name))
			}
		}
		namedStr := strings.Join(named, ", ")
		switch f.Kind {
		case FuncNoun:
			recv := fmt.Sprintf("%s.%s.valueOf(_n(value))!", dartAlias(f.Enum), enumTypeName(f.Enum))
			arg := "l"
			if namedStr != "" {
				arg += ", " + namedStr
			}
			fmt.Fprintf(&b, "      return %s.uiText(%s);\n", recv, arg)
		case FuncVariant:
			recv := fmt.Sprintf("%s.%s.valueOf(_n(value))!", dartAlias(f.Enum), enumTypeName(f.Enum))
			arg := "l"
			if namedStr != "" {
				arg += ", " + namedStr
			}
			fmt.Fprintf(&b, "      return %s.%s(%s);\n", recv, lowerCamel(f.Variant), arg)
		case FuncSentence:
			arg := "l"
			if namedStr != "" {
				arg += ", " + namedStr
			}
			fmt.Fprintf(&b, "      return %s(%s);\n", lowerFirst(pascal(f.ID)), arg)
		case FuncUnknown:
			b.WriteString("      return commonUnknown(l);\n")
		case FuncError:
			b.WriteString("      return commonErrorText(_codes[value]!, l);\n")
		}
	}
	b.WriteString("  }\n  throw ArgumentError('unknown golden fn $fn');\n}\n")
	return []byte(b.String())
}
