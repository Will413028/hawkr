// useList 是可重複的 -use <擁有者>:<pub 函式>。
type useList []string

func (u *useList) String() string     { return strings.Join(*u, ",") }
func (u *useList) Set(v string) error { *u = append(*u, v); return nil }

func runPub(args []string) error {
	fl := flag.NewFlagSet("pub", flag.ContinueOnError)
	module := fl.String("module", "", "消費端模組（只用來寫進檔頭）")
	out := fl.String("out", "", "輸出目錄（先清空）")
	root := fl.String("modules-dir", "internal/modules", "模組目錄")
	var uses useList
	fl.Var(&uses, "use", "要包裝的 pub 函式，格式 <擁有者>:<函式名>，可重複")
	if err := fl.Parse(args); err != nil {
		return err
	}
	if *module == "" || *out == "" || len(uses) == 0 {
		return fmt.Errorf("pub 需要 -module、-out 與至少一個 -use")
	}
	byOwner := map[string][]string{}
	for _, u := range uses {
		owner, fn, ok := strings.Cut(u, ":")
		if !ok || owner == "" || fn == "" {
			return fmt.Errorf("-use %q 的格式是 <擁有者>:<函式名>", u)
		}
		if !slices.Contains(arch.Dependencies[*module], owner) {
			return fmt.Errorf("依賴表（internal/arch 的 Dependencies）不允許模組 %s 依賴 %s，不能為它生成 pub 包裝", *module, owner)
		}
		byOwner[owner] = append(byOwner[owner], fn)
	}
	owners := make([]string, 0, len(byOwner))
	for o := range byOwner {
		owners = append(owners, o)
	}
	sort.Strings(owners)
	if err := os.RemoveAll(*out); err != nil {
		return err
	}
	if err := os.MkdirAll(*out, 0o755); err != nil { //nolint:gosec // 生成的原始碼目錄要能被一般使用者走訪
		return err
	}
	for _, owner := range owners {
		src := filepath.Join(*root, owner, "db", "pub.sql")
		body, err := os.ReadFile(src) //nolint:gosec // 路徑由 -modules-dir、依賴表允許的擁有者與固定檔名組成
		if err != nil {
			return err
		}
		code, err := GeneratePub(owner, filepath.ToSlash(src), string(body), byOwner[owner])
		if err != nil {
			return fmt.Errorf("%s：%w", src, err)
		}
		if err := os.WriteFile(filepath.Join(*out, owner+".go"), code, 0o644); err != nil { //nolint:gosec // 生成的原始碼本來就是可讀的
			return err
		}
	}
	return nil
}

// pubTable 是 pub.sql 宣告的一張形狀表（pub_* 函式回傳的列）。
type pubTable struct {
	cols []pubCol
}

type pubCol struct{ name, typ string }

type pubFunc struct {
	name   string
	params []pubCol
	ret    string // 回傳的形狀表名
}

// jetTypes 把 SQL 型別對到 jet 的運算式型別；不在表內的型別要先擴充這裡（生成失敗比包裝成錯的型別好）。
var jetTypes = map[string]string{
	"int2": "IntegerExpression", "int4": "IntegerExpression", "int8": "IntegerExpression",
	"text": "StringExpression", "varchar": "StringExpression", "uuid": "StringExpression",
	"timestamptz": "TimestampzExpression", "bool": "BoolExpression", "date": "DateExpression",
}

// GeneratePub 由擁有者的 pub.sql 為 uses 列出的函式生成包裝：對函式回傳的每一欄生成 `<擁有者><函式><欄>Has`，
// 即 EXISTS (SELECT 1 FROM <擁有者>.<函式>(參數) AS pub WHERE pub.<欄> = <值> [AND (<額外條件>)])。額外條件放在子查詢裡，
// 外層的 NOT EXISTS 才保持 anti-join（呼叫端把外層列的條件推進來）。
func GeneratePub(owner, srcPath, sql string, uses []string) ([]byte, error) {
	tree, err := pg_query.Parse(sql)
	if err != nil {
		return nil, err
	}
	tables := map[string]*pubTable{}
	funcs := map[string]pubFunc{}
	for _, raw := range tree.Stmts {
		if cs := raw.Stmt.GetCreateStmt(); cs != nil && cs.Relation.Schemaname == owner {
			t := &pubTable{}
			for _, el := range cs.TableElts {
				if cd := el.GetColumnDef(); cd != nil {
					t.cols = append(t.cols, pubCol{cd.Colname, typeName(cd.TypeName)})
				}
			}
			tables[cs.Relation.Relname] = t
		}
		if fs := raw.Stmt.GetCreateFunctionStmt(); fs != nil && len(fs.Funcname) == 2 && fs.Funcname[0].GetString_().Sval == owner {
			f := pubFunc{name: fs.Funcname[1].GetString_().Sval}
			for _, p := range fs.Parameters {
				fp := p.GetFunctionParameter()
				f.params = append(f.params, pubCol{fp.Name, typeName(fp.ArgType)})
			}
			if fs.ReturnType == nil || !fs.ReturnType.Setof || len(fs.ReturnType.Names) != 2 {
				return nil, fmt.Errorf("函式 %s 必須宣告成 RETURNS SETOF %s.<形狀表>", f.name, owner)
			}
			f.ret = fs.ReturnType.Names[1].GetString_().Sval
			funcs[f.name] = f
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/jetgen from %s. DO NOT EDIT.\n\n", srcPath)
	b.WriteString("package pubsql\n\nimport . \"github.com/go-jet/jet/v2/postgres\"\n")
	sort.Strings(uses)
	for _, name := range uses {
		f, ok := funcs[name]
		if !ok {
			return nil, fmt.Errorf("pub.sql 沒有函式 %s.%s", owner, name)
		}
		if !strings.HasPrefix(name, "pub_") {
			return nil, fmt.Errorf("%s.%s 不是 pub_*", owner, name)
		}
		t, ok := tables[f.ret]
		if !ok {
			return nil, fmt.Errorf("pub.sql 沒有函式 %s 回傳的形狀表 %s.%s", name, owner, f.ret)
		}
		for _, p := range f.params {
			if jetTypes[p.typ] == "" {
				return nil, fmt.Errorf("%s 的參數 %s 的型別 %q 不在 jetTypes 裡，先擴充 cmd/jetgen/pub.go", name, p.name, p.typ)
			}
		}
		for _, c := range t.cols {
			if jetTypes[c.typ] == "" {
				return nil, fmt.Errorf("%s 回傳的欄位 %s 的型別 %q 不在 jetTypes 裡，先擴充 cmd/jetgen/pub.go", name, c.name, c.typ)
			}
			emitHas(&b, owner, f, c)
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("生成的程式碼不合法：%w\n%s", err, b.String())
	}
	return out, nil
}

func emitHas(b *bytes.Buffer, owner string, f pubFunc, c pubCol) {
	fnGo := camel(strings.TrimPrefix(f.name, "pub_"))
	ident := camel(owner) + fnGo + "Has" + camel(c.name)
	colT := jetTypes[c.typ]
	var sig, parts []string
	for i, p := range f.params {
		sig = append(sig, lowerFirst(camel(p.name))+" "+jetTypes[p.typ])
		if i > 0 {
			parts = append(parts, `Token(",")`)
		}
		parts = append(parts, lowerFirst(camel(p.name)))
	}
	val := lowerFirst(camel(c.name))
	if val == "type" || val == "func" {
		val += "Value"
	}
	fmt.Fprintf(b, "\n// %s 是 EXISTS (SELECT 1 FROM %s.%s(…) AS pub WHERE pub.%s = %s [AND (and…)])。and 放在子查詢裡。\n", ident, owner, f.name, c.name, val)
	fmt.Fprintf(b, "func %s(%s%s %s, and ...BoolExpression) BoolExpression {\n", ident, joinComma(sig), sepIf(len(sig) > 0), val+" "+colT)
	fmt.Fprintf(b, "\tparts := []Serializer{Token(\"EXISTS (SELECT 1 FROM %s.%s(\")", owner, f.name)
	for _, p := range parts {
		fmt.Fprintf(b, ", %s", p)
	}
	fmt.Fprintf(b, ", Token(\") AS pub WHERE pub.%s =\"), %s}\n", c.name, val)
	b.WriteString("\tfor _, a := range and {\n\t\tparts = append(parts, Token(\"AND (\"), a, Token(\")\"))\n\t}\n")
	b.WriteString("\tparts = append(parts, Token(\")\"))\n\treturn BoolExp(CustomExpression(parts...))\n}\n")
}

func joinComma(s []string) string { return strings.Join(s, ", ") }

func sepIf(c bool) string {
	if c {
		return ", "
	}
	return ""
}

func typeName(t *pg_query.TypeName) string {
	if t == nil || len(t.Names) == 0 {
		return ""
	}
	return t.Names[len(t.Names)-1].GetString_().Sval
}

func camel(s string) string {
	var b strings.Builder
	for _, w := range strings.Split(s, "_") {
		if w == "" {
			continue
		}
		if w == "id" {
			b.WriteString("ID")
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	if strings.HasPrefix(s, "ID") {
		return "id" + s[2:]
	}
	return strings.ToLower(s[:1]) + s[1:]
}
