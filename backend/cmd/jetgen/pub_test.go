package main

import (
	"strings"
	"testing"
)

const samplePub = `
CREATE SCHEMA seller;
CREATE TABLE seller.pub_exposable_store (store_id BIGINT NOT NULL);
CREATE FUNCTION seller.pub_exposable_stores(at TIMESTAMPTZ) RETURNS SETOF seller.pub_exposable_store
LANGUAGE sql STABLE AS $$ SELECT * FROM seller.pub_exposable_store $$;
CREATE TABLE seller.pub_review_item (kind TEXT NOT NULL, due_at TIMESTAMPTZ NOT NULL, extra NUMERIC);
CREATE FUNCTION seller.pub_review_items(at TIMESTAMPTZ) RETURNS SETOF seller.pub_review_item
LANGUAGE sql STABLE AS $$ SELECT * FROM seller.pub_review_item $$;
`

// 每個回傳欄位一個 `<擁有者><函式><欄>Has` 包裝，參數與欄位的型別對到 jet 的運算式型別；原始 SQL 的片段在生成檔裡。
func TestGeneratePubWrapsEveryReturnedColumn(t *testing.T) {
	out, err := GeneratePub("seller", "internal/modules/seller/db/pub.sql", samplePub, []string{"pub_exposable_stores"})
	if err != nil {
		t.Fatal(err)
	}
	got := string(out)
	for _, want := range []string{
		"Code generated by cmd/jetgen from internal/modules/seller/db/pub.sql. DO NOT EDIT.",
		"func SellerExposableStoresHasStoreID(at TimestampzExpression, storeID IntegerExpression, and ...BoolExpression) BoolExpression",
		`Token("EXISTS (SELECT 1 FROM seller.pub_exposable_stores(")`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("生成檔缺 %q：\n%s", want, got)
		}
	}
	if strings.Contains(got, "ReviewItems") {
		t.Errorf("沒列在 -use 的函式不該生成：\n%s", got)
	}
}

func TestGeneratePubRefusesWhatItCannotType(t *testing.T) {
	if _, err := GeneratePub("seller", "x", samplePub, []string{"pub_review_items"}); err == nil || !strings.Contains(err.Error(), "numeric") {
		t.Errorf("不認得的欄位型別要報錯：%v", err)
	}
	if _, err := GeneratePub("seller", "x", samplePub, []string{"pub_nope"}); err == nil {
		t.Error("pub.sql 沒有的函式要報錯")
	}
	if _, err := GeneratePub("seller", "x", samplePub, []string{"pub_exposable_store"}); err == nil {
		t.Error("不是函式的名稱要報錯")
	}
}
