-- 建立 updated_at 自動更新觸發器函數
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- -----------------------------------------------------
-- 1. 商品分類表（作為 product.category 的 FK 目標）
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS category (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    parent_id BIGINT REFERENCES category(id),
    status VARCHAR(20) NOT NULL DEFAULT '9004',
    created_by VARCHAR(50) NOT NULL DEFAULT 'system',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by VARCHAR(50),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_category_created_at ON category(created_at);
CREATE INDEX IF NOT EXISTS idx_category_status ON category(status);
-- 防止併發寫入時產生同一父分類下的重複名稱
CREATE UNIQUE INDEX IF NOT EXISTS uk_category_name_parent
    ON category(name, COALESCE(parent_id, 0));

DROP TRIGGER IF EXISTS update_category_updated_at ON category;
CREATE TRIGGER update_category_updated_at
    BEFORE UPDATE ON category
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE category IS '商品分類表 - 作為 product.category 的 FK 目標';
COMMENT ON COLUMN category.status IS '分類狀態 - CommonStatus（9003=軟刪除, 9004=啟用）';
COMMENT ON COLUMN category.updated_by IS '更新者';
COMMENT ON COLUMN category.updated_at IS '更新時間（由 DB 觸發器自動更新）';
COMMENT ON COLUMN category.deleted_at IS '軟刪除時間（status=9003 時與 updated_at 同步寫入；還原時清空）';

-- -----------------------------------------------------
-- 2. 商品主表（設計書 2.1）
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS product (
    id BIGINT PRIMARY KEY,                              -- TSID (時序 ID)
    name VARCHAR(255) NOT NULL,
    rating DECIMAL(3, 2),
    status VARCHAR(4) NOT NULL DEFAULT '4002',          -- 4001=草稿, 4002=審核中, 4003=未啟用, 4004=啟用
    category BIGINT NOT NULL REFERENCES category(id),
    category_lv2 BIGINT NOT NULL REFERENCES category(id),  -- 第二層分類 ID（反正規化，由後端自動從 category.parent_id 填入）
    category_lv1 BIGINT NOT NULL REFERENCES category(id),  -- 第一層分類 ID（反正規化，由後端自動從 category_lv2.parent_id 填入）
    cat_l1_name VARCHAR(100),                           -- 第一層分類名稱快照（寫入時 lookup；分類改名觸發 cascade reflow）
    cat_l2_name VARCHAR(100),                           -- 第二層分類名稱快照
    cat_l3_name VARCHAR(100),                           -- 第三層分類名稱快照（等同 product.category 對應 category.name）
    origin TEXT,
    description JSONB,
    pure_description TEXT,                              -- 純文字描述（從 description.blocks[?type=text].content + image.alt 萃取串接）
    searchable_text TEXT,                               -- 檢索全文（name + pure_description + cat_l*_name + sku_names + hashtag canonical names；上限 8 KB）
    gallery JSONB DEFAULT '[]'::jsonb,
    certifications JSONB DEFAULT '[]'::jsonb,
    price_min BIGINT,                                   -- 最低實際售價（新台幣元，彙總自 SKU effective_price = sale_price ?? price）
    price_max BIGINT,                                   -- 最高實際售價（新台幣元）
    list_price_min BIGINT,                              -- 最低原價（新台幣元，彙總自 SKU.price，給前端 strike-through 用）
    list_price_max BIGINT,                              -- 最高原價（新台幣元）
    sale_price_min BIGINT,                              -- 最低特價（新台幣元，彙總自 SKU.sale_price；皆無特價則 NULL）
    sale_price_max BIGINT,                              -- 最高特價（新台幣元）
    sales_count BIGINT NOT NULL DEFAULT 0,              -- 累計銷量（付款成功時 +N，反正規化；詳見 35 設計書）
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by BIGINT,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    updated_by BIGINT,
    deleted_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_product_name ON product(name);
CREATE INDEX IF NOT EXISTS idx_product_status ON product(status);
CREATE INDEX IF NOT EXISTS idx_product_category ON product(category);
CREATE INDEX IF NOT EXISTS idx_product_category_lv2 ON product(category_lv2);
CREATE INDEX IF NOT EXISTS idx_product_category_lv1 ON product(category_lv1);
CREATE INDEX IF NOT EXISTS idx_product_price_min ON product(price_min);
CREATE INDEX IF NOT EXISTS idx_product_price_max ON product(price_max);
CREATE INDEX IF NOT EXISTS idx_product_created_at ON product(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_product_created_by ON product(created_by);
CREATE INDEX IF NOT EXISTS idx_product_deleted_at ON product(deleted_at) WHERE deleted_at IS NULL;
-- 複合索引（使用 category_lv2 / category_lv1 支援多層分類檢索）
CREATE INDEX IF NOT EXISTS idx_product_query ON product(status, category_lv2, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_product_query_lv1 ON product(status, category_lv1, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_product_price_sort ON product(status, price_min, price_max);

-- 02 §5.3.4 多賣家篩選（seller_account_ids）+ 既有單一賣家頁面：複合索引涵蓋兩種場景
CREATE INDEX IF NOT EXISTS idx_product_status_created_by ON product(status, created_by);

-- 02 §5.13 公開產地聚合 partial index
-- 注意：partial 條件中 '4004' 對應 ProductStatus.ACTIVE，若 enum value 變更需同步更新
CREATE INDEX IF NOT EXISTS idx_product_origin_active
    ON product(origin)
    WHERE deleted_at IS NULL AND status = '4004' AND origin IS NOT NULL AND origin <> '';
-- 多 token OR 模糊檢索 GIN trgm 索引（搭 §5.3.3 規則）
CREATE INDEX IF NOT EXISTS idx_product_search_trgm
    ON product USING gin (searchable_text gin_trgm_ops)
    WHERE deleted_at IS NULL;

-- 商品列表排序 partial index（35 設計書 §3.2）
-- 涵蓋 5 種 ProductSort 排序鍵，partial 條件帶入「已上架且未刪除」以縮小索引並啟用 index-only scan
CREATE INDEX IF NOT EXISTS idx_product_active_created_at
    ON product (created_at DESC)
    WHERE deleted_at IS NULL AND status = '4004';
CREATE INDEX IF NOT EXISTS idx_product_active_price_min
    ON product (price_min ASC NULLS LAST)
    WHERE deleted_at IS NULL AND status = '4004';
CREATE INDEX IF NOT EXISTS idx_product_active_price_max
    ON product (price_max DESC NULLS LAST)
    WHERE deleted_at IS NULL AND status = '4004';
CREATE INDEX IF NOT EXISTS idx_product_active_rating
    ON product (rating DESC NULLS LAST, created_at DESC)
    WHERE deleted_at IS NULL AND status = '4004';
CREATE INDEX IF NOT EXISTS idx_product_active_sales
    ON product (sales_count DESC, created_at DESC)
    WHERE deleted_at IS NULL AND status = '4004';

DROP TRIGGER IF EXISTS update_product_updated_at ON product;
CREATE TRIGGER update_product_updated_at
    BEFORE UPDATE ON product
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE product IS '商品主表 - 設計書 2.1';
COMMENT ON COLUMN product.price_min IS '最低實際售價（新台幣元，彙總自 SKU effective_price = sale_price ?? price）';
COMMENT ON COLUMN product.price_max IS '最高實際售價（新台幣元）';
COMMENT ON COLUMN product.list_price_min IS '最低原價（新台幣元，彙總自 SKU.price，給前端 strike-through 顯示）';
COMMENT ON COLUMN product.list_price_max IS '最高原價（新台幣元）';
COMMENT ON COLUMN product.sale_price_min IS '最低特價（新台幣元，彙總自 SKU.sale_price；皆無特價時為 NULL）';
COMMENT ON COLUMN product.sale_price_max IS '最高特價（新台幣元）';

-- -----------------------------------------------------
-- 3. 商品 SKU 表（設計書 2.2）
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS product_sku (
    id BIGSERIAL PRIMARY KEY,                           -- 自增主鍵（內部使用）
    product_id BIGINT NOT NULL REFERENCES product(id),
    sku_name VARCHAR(100) NOT NULL DEFAULT '1',
    weight DECIMAL(10, 3),
    unit VARCHAR(20) NOT NULL,
    price BIGINT NOT NULL,                              -- 原價（新台幣元）
    sale_price BIGINT CHECK (sale_price IS NULL OR (sale_price > 0 AND sale_price < price)),  -- 特價（新台幣元，NULL=無特價；非 NULL 必須 > 0 且 < price）
    stock_qty INTEGER NOT NULL DEFAULT 0 CHECK (stock_qty >= 0),
    length_cm DECIMAL(10, 2),
    width_cm DECIMAL(10, 2),
    height_cm DECIMAL(10, 2),
    shipping_method JSONB NOT NULL DEFAULT '[]'::jsonb,  -- 運送方式 [{type, temperature, freeThreshold, feePayer}]
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_product_sku_product_id ON product_sku(product_id);
CREATE INDEX IF NOT EXISTS idx_product_sku_name ON product_sku(sku_name);
CREATE INDEX IF NOT EXISTS idx_product_sku_unit ON product_sku(unit);
CREATE INDEX IF NOT EXISTS idx_product_sku_price ON product_sku(price);

DROP TRIGGER IF EXISTS update_product_sku_updated_at ON product_sku;
CREATE TRIGGER update_product_sku_updated_at
    BEFORE UPDATE ON product_sku
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE product_sku IS '商品 SKU 表 - 設計書 2.2';
COMMENT ON COLUMN product_sku.price IS '原價（新台幣元，list price）';
COMMENT ON COLUMN product_sku.sale_price IS '特價（新台幣元，NULL=無特價，非 NULL 必須 > 0 且 < price）。實際成交單價 = sale_price ?? price';

