-- -----------------------------------------------------
-- 5. 庫存交易冪等表（庫存扣減/歸還冪等性保證）
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS stock_transaction (
    stock_tx_id VARCHAR(64) NOT NULL,             -- Order Service 生成，用於冪等
    operation VARCHAR(10) NOT NULL,               -- DEDUCT / RESTORE
    payload JSONB NOT NULL DEFAULT '[]'::jsonb,   -- [{sku_id, quantity}]
    status VARCHAR(10) NOT NULL DEFAULT '8912',   -- StockTxStatus.SUCCESS
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (stock_tx_id, operation)           -- 同一 txId 可分別記錄 DEDUCT 和 RESTORE
);

CREATE INDEX IF NOT EXISTS idx_stock_tx_operation ON stock_transaction(operation);
CREATE INDEX IF NOT EXISTS idx_stock_tx_created_at ON stock_transaction(created_at);

COMMENT ON TABLE stock_transaction IS '庫存交易冪等表 - 保證 DeductStock/RestoreStock 冪等性';

-- -----------------------------------------------------
-- 6. Hashtag 主表（設計書 3.7）
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS hashtag (
    id BIGINT PRIMARY KEY,                              -- TSID（與 product 共用 generator）
    name VARCHAR(40) NOT NULL,                          -- canonical 名稱（normalize 後）
    product_count INTEGER NOT NULL DEFAULT 0,           -- 引用計數（僅算 ACTIVE 且未刪商品）
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_hashtag_name ON hashtag(name);
CREATE INDEX IF NOT EXISTS idx_hashtag_name_pattern ON hashtag(name varchar_pattern_ops);
CREATE INDEX IF NOT EXISTS idx_hashtag_name_trgm ON hashtag USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_hashtag_popular ON hashtag(product_count DESC, name);

DROP TRIGGER IF EXISTS update_hashtag_updated_at ON hashtag;
CREATE TRIGGER update_hashtag_updated_at
    BEFORE UPDATE ON hashtag
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE hashtag IS 'Hashtag 主表 - 設計書 3.7';
COMMENT ON COLUMN hashtag.name IS 'canonical 名稱（trim+strip#+NFC+lower），UNIQUE';
COMMENT ON COLUMN hashtag.product_count IS '引用計數，僅算 status=4004 且 deleted_at IS NULL 的商品；同事務 row-lock 維護（單一寫入路徑為唯一真實來源，詳見設計書 33 §4）';

-- -----------------------------------------------------
-- 7. Product-Hashtag 關聯表（設計書 3.8）
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS product_hashtag (
    product_id BIGINT NOT NULL REFERENCES product(id),
    hashtag_id BIGINT NOT NULL REFERENCES hashtag(id),
    display_name VARCHAR(40) NOT NULL,                  -- 賣家輸入的原大小寫（trim+strip#+NFC，不 lower）
    position SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (product_id, hashtag_id)
);

CREATE INDEX IF NOT EXISTS idx_product_hashtag_lookup ON product_hashtag(hashtag_id, product_id);
CREATE INDEX IF NOT EXISTS idx_product_hashtag_created_at ON product_hashtag(created_at, hashtag_id);

COMMENT ON TABLE product_hashtag IS 'product-hashtag 關聯表 - 設計書 3.8';
COMMENT ON COLUMN product_hashtag.display_name IS '賣家輸入時保留原大小寫的版本，per-binding（與 IG 一致）';
COMMENT ON COLUMN product_hashtag.position IS '賣家編輯時順序，0 起算，詳情頁 hashtag list 依此升序';

