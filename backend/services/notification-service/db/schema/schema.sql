CREATE TABLE "device_tokens" (
  "id" bigint NOT NULL,
  "user_id" bigint NOT NULL,
  "user_type" varchar(10) NOT NULL, -- 'buyer' | 'seller'
  "token" text NOT NULL,
  "platform" varchar(10) NOT NULL,  -- 'android' | 'ios'
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uni_device_tokens_user_token" UNIQUE ("user_id", "user_type", "token")
);
CREATE INDEX "idx_device_tokens_user" ON "device_tokens" ("user_id", "user_type");

CREATE TABLE "notifications" (
  "id" bigint NOT NULL,
  "user_id" bigint NOT NULL,
  "user_type" varchar(10) NOT NULL,
  "event_type" varchar(100) NOT NULL,
  "reference_id" varchar(100),
  "title" text NOT NULL,
  "body" text NOT NULL,
  "data" jsonb,
  "is_read" boolean NOT NULL DEFAULT false,
  "read_at" timestamptz,
  "deleted_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);
CREATE INDEX "idx_notifications_user" ON "notifications" ("user_id", "user_type");
CREATE INDEX "idx_notifications_inbox" ON "notifications" ("user_id", "user_type", "id" DESC) WHERE "deleted_at" IS NULL;
CREATE INDEX "idx_notifications_unread" ON "notifications" ("user_id", "user_type") WHERE "deleted_at" IS NULL AND "is_read" = false;
CREATE INDEX "idx_notifications_cleanup_deleted" ON "notifications" ("deleted_at") WHERE "deleted_at" IS NOT NULL;
CREATE UNIQUE INDEX "notifications_inbox_dedup_idx" ON "notifications" ("user_id", "user_type", "event_type", "reference_id") WHERE "reference_id" IS NOT NULL;

CREATE TABLE "notification_preferences" (
  "id" bigserial NOT NULL,
  "user_id" bigint NOT NULL,
  "user_type" varchar(10) NOT NULL, -- 'buyer' | 'seller'
  "category" varchar(30) NOT NULL,  -- 'order_update' | 'refund_update' | 'system' | 'chat' | 'follower' | 'post'
  "enabled" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uni_notification_preferences_user_category" UNIQUE ("user_id", "user_type", "category")
);
CREATE INDEX "idx_notification_preferences_user" ON "notification_preferences" ("user_id", "user_type");

CREATE TABLE "notification_templates" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "exchange" varchar(100) NOT NULL,
  "routing_key" varchar(200) NOT NULL,
  "event_type" varchar(100) NOT NULL,
  "target_user_type" varchar(10) NOT NULL,     -- 'buyer' | 'seller'
  "target_user_field" varchar(100) NOT NULL,   -- payload 欄位名稱，用於取得 user_id
  "category" varchar(30) NOT NULL,             -- 通知偏好分類
  "title_template" text NOT NULL,              -- #{fieldName} 語法
  "body_template" text NOT NULL,               -- #{fieldName} 語法
  "body_fallback" text,                        -- 渲染失敗時的 fallback 文案
  "data_type" varchar(100) NOT NULL,           -- FCM data.type 值
  "data_fields" jsonb,                         -- {fcm_key: payload_field_name}
  "schema_url" varchar(500),                   -- deep link，{} 引用 data_fields 映射後的 key
  "reference_id_template" varchar(200),        -- 冪等 ID 模板，#{fieldName} 語法
  "image_key_template" text,                   -- imageUrl 模板，#{fieldName} 語法；NULL = 不附圖
  "payload_filter" jsonb,                      -- e.g. {"status": "IN_TRANSIT"}; null = 不過濾
  "enabled" boolean NOT NULL DEFAULT true,
  "push_mode" varchar(10) NOT NULL DEFAULT 'visible', -- 'visible' = banner+inbox；'silent' = data-only push 不寫 inbox
  "identity_migrated" boolean NOT NULL DEFAULT false, -- seller template 是否已完成 store_id cutover；保留作 migration audit，constraint 禁止 seller 回到 account_id；buyer 側無意義
  "updated_by" bigint,
  "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uni_notification_templates_event_user_type" UNIQUE ("event_type", "target_user_type"),
  CONSTRAINT "chk_notification_templates_seller_identity_migrated"
    CHECK ("target_user_type" <> 'seller' OR "identity_migrated" = true)
);
CREATE INDEX "idx_notification_templates_enabled" ON "notification_templates" ("enabled");

CREATE TABLE "push_notifications" (
  "id" bigint NOT NULL,
  "user_id" bigint NOT NULL,
  "user_type" varchar(10) NOT NULL,
  "event_type" varchar(100) NOT NULL,
  "reference_id" varchar(100),
  "status" varchar(20) NOT NULL,
  "error_log" text,
  "sent_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);
CREATE INDEX "push_notifications_user_idx" ON "push_notifications" ("user_id", "user_type");
CREATE UNIQUE INDEX "push_notifications_dedup_idx" ON "push_notifications" ("user_id", "user_type", "event_type", "reference_id") WHERE "status" = 'sent' AND "reference_id" IS NOT NULL;

-- Admin 系統通知 audit log（SYSTEM_MAINTENANCE / TERMS_UPDATE 廣播紀錄）
-- hybrid 流程：admin RPC 寫 status=pending → worker 消 MQ 後 update sent/failed
CREATE TABLE "system_notification_logs" (
  "id" bigint NOT NULL,                                         -- TSID
  "notification_type" varchar(40) NOT NULL,                     -- 'SYSTEM_MAINTENANCE' | 'TERMS_UPDATE'
  "title" text NOT NULL,
  "body" text NOT NULL,
  "image_key" text,
  "deep_link_url" text,
  "content_hash" char(64) NOT NULL,                             -- sha256(type|title|body|imageUrl|url) idempotency key
  "triggered_by_account_id" bigint NOT NULL,                    -- admin account
  "triggered_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "fcm_message_id" text,                                        -- FCM 回傳 message ID
  "status" varchar(20) NOT NULL DEFAULT 'pending',              -- 'pending' | 'sent' | 'failed'
  "failed_reason" text,
  "completed_at" timestamptz,
  PRIMARY KEY ("id")
);
CREATE INDEX "idx_system_notification_logs_triggered_at" ON "system_notification_logs" ("triggered_at" DESC);
CREATE INDEX "idx_system_notification_logs_content_hash" ON "system_notification_logs" ("content_hash", "triggered_at" DESC);
