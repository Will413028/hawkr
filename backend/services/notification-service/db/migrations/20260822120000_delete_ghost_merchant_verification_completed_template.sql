-- 刪除幽靈 template `merchant.verification.completed`（baseline 中的 id = 11）。
--
-- 「幽靈」＝**沒有任何 publisher 會發出這個 event**，所以它永遠不可能被觸發：
-- seller-service 的 MerchantEventPublisher（services/seller-service/internal/mq/
-- merchant_event_publisher.go:16-19）按審核結果把 routing key 拆成四支，本 template
-- 綁的那一支不在其中：
--
--   merchant.verification.approved
--   merchant.verification.rejected
--   merchant.verification.pending_info
--   merchant.verification.forwarded
--
-- 四支各自有自己的 enabled template（20260701120000 / 20260703120000），本 row 自
-- 20260703120000 起就是 enabled = false（dev + prod 實查一致），且欄位還停在
-- camelCase 的 `merchantId`，與四支分流 template 的 snake_case `merchant_id` 不一致
-- —— 就算有人把它打開也對不上 payload。
--
-- 證據（2026-08-22 實查）：`rg '"merchant.verification.completed"'` 在排除 docs/、
-- tests/contract/golden/、services/notification-service/db/ 之後**零命中**；
-- tests/contract/golden/event_payload_keys.json 從來就沒有這個 event 的條目，所以
-- 刪除它不需要同步刪 golden，只要移除 known_pending_identity.json 的追蹤條目。
--
-- 明確不動 `procurement.quote_invite.created` / `.lost`（20260815120000）：那兩支的
-- enabled = false 帶著 33 行檔頭說明與三條解除條件，是「publisher 尚未落地」而不是
-- 「publisher 不存在」，並仍列在 known_pending.json 追蹤中。
--
-- 用 (event_type, target_user_type) 而不是 id：那組是 uni_notification_templates_
-- event_user_type 的唯一鍵，而 id 欄位在 20260703130000 之後是 GENERATED BY DEFAULT
-- AS IDENTITY，baseline 對既有 DB 走 ON CONFLICT DO UPDATE **保留原 id**——遠端的
-- id 未必等於 baseline 檔案裡的 11。
DELETE FROM notification_templates
WHERE event_type = 'merchant.verification.completed'
  AND target_user_type = 'seller';
