-- 刪除 legacy 報價單邀請的兩支 seller template（C3／T18 quote-invite 退場）。
--
-- doc 64 §7 明列 legacy quote-invite 與 quote-batches 的 preview／create／withdraw
-- 整條退場，唯一的 side-effect 入口改為 publication approval → execute。V6 的對應
-- template 是 procurement.rfq_publication_invite.*（20260910120000），兩者是不同
-- 管道、不同表，不共用任何一列。
--
-- 這兩支自 20260904100000 起是 enabled = true，publisher 是 ai-service 的
-- quote_invite_publisher.go（PLATFORM lane 實際發過 MQ）。本 migration 隨 gateway
-- 路由與 ai-service RPC 的退場一起刪除它們——publisher 走了之後這兩支再也不會被
-- 觸發，留著就是下一個人排查時的幽靈。
--
-- 用 (event_type, target_user_type) 而不是 id：那組是 uni_notification_templates_
-- event_user_type 的唯一鍵，而 id 在 20260703130000 之後是 GENERATED BY DEFAULT AS
-- IDENTITY，baseline 對既有 DB 走 ON CONFLICT DO UPDATE 保留原 id，遠端的 id 未必
-- 等於檔案裡的值。
--
-- ⚠️ 與 20260822120000（刪幽靈 template）不同的是：那次 golden 沒有對應條目所以不用
-- 動，這次 tests/contract/golden/event_payload_keys.json 有
-- procurement.quote_invite.created.seller / .lost.seller 兩筆，已在同一刀移除。
DELETE FROM notification_templates
WHERE event_type IN (
    'procurement.quote_invite.created.seller',
    'procurement.quote_invite.lost.seller'
  )
  AND target_user_type = 'seller';
