-- 刪除三支幽靈 template：系統公告與兩支系統廣播（baseline 中的 id = 12 / 101 / 102）。
--
-- 「幽靈」＝**沒有任何 publisher 會發出這個 event**，所以 template 永遠不可能被觸發。
-- 三支的形狀不同，證據分開列（2026-08-22 實查）：
--
-- 1) notification.announcement（id 12, seller, exchange hawkr.notification）
--    路由鍵常數 `RoutingKeyNotificationAnnouncement`（pkg/mq/exchanges.go）全 repo
--    只有宣告、**零 publish 呼叫點**。真正在發公告的是 gRPC
--    `BroadcastAnnouncement`（internal/grpc/server_broadcast.go），它自己寫
--    notifications ＋ push_notifications，完全不經 MQ。也就是說公告一直有兩條寫入
--    路徑：一條活著但繞過模板引擎，一條掛著 enabled template 卻沒有生產者。
--    本次收斂成前者（模板引擎的 per-recipient 形狀需要 N 個事件，而收件人名單只有
--    notification-service 自己有，走 MQ 等於自產自銷），故本 row 一併刪除。
--
-- 2) notification.system.maintenance（id 101, buyer）
-- 3) notification.terms.update（id 102, buyer）
--    兩者的 routing_key 都是 `notification.system.broadcast`——這個字串全 repo 零命中
--    （連常數都不存在），tests/contract/golden/event_payload_keys.json 對它們的
--    `publisher` 自陳 "unknown"（全檔僅有的 2 筆）。兩支走的 `broadcastTemplate`
--    分支**完全不寫 inbox 也不寫 push_notifications**，就算有人補上 publisher，
--    收件人也只會看到一則轉瞬即逝的 FCM banner，事後在收件匣裡什麼都找不到。
--    `fcm_topic` 全表只有這 2 列非空，刪掉之後該欄位在 DB 內已無任何非空值。
--
-- ⚠️ **本 migration 刻意不做 `ALTER TABLE notification_templates DROP COLUMN fcm_topic`**
--    （expand-contract 的第二步，留給後續 migration）。順序約束：
--    db/queries/notification_templates.sql 的四支 query 都明列 fcm_topic，sqlc 生成的
--    scan 也帶著它。若欄位先於「讀取端已下線的版本」部署，舊 pod 每 5 分鐘一次的
--    template cache refresh 會全部報錯，而 refresh 外層有 panic guard ＋ 保留舊快取
--    ⇒ **不會 crash、不會進 DLQ，只會靜默停止更新模板**。所以順序必須是：
--    (a) 本 migration ＋ 移除 Go 讀取端 → 部署完成 →
--    (b) 才輪到下一支 migration DROP COLUMN（屆時 queries/sqlc gen 一併移除）。
--
-- 用 (event_type, target_user_type) 而不是 id：那組是 uni_notification_templates_
-- event_user_type 的唯一鍵，而 id 欄位在 20260703130000 之後是 GENERATED BY DEFAULT
-- AS IDENTITY，baseline 對既有 DB 走 ON CONFLICT DO UPDATE **保留原 id**——遠端的
-- id 未必等於 baseline 檔案裡的 12 / 101 / 102。
DELETE FROM notification_templates
WHERE (event_type, target_user_type) IN (
  ('notification.announcement', 'seller'),
  ('notification.system.maintenance', 'buyer'),
  ('notification.terms.update', 'buyer')
);
