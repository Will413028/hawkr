func TestRenderAliasFile_IsValidGoAndSorted(t *testing.T) {
	cabbage := node{ID: "117", Name: "甘藍", Level: 2, L1Name: "蔬菜"}
	burdock := node{ID: "64", Name: "牛蒡", Level: 2, L1Name: "蔬菜"}
	out, err := renderAliasFile([]candidate{
		{Alias: "牛蒡根", Target: burdock},
		{Alias: "捲心菜", Target: cabbage},
	}, renderMeta{Model: "test-model", Samples: 3, MinAgree: 2, L2Count: 2, NodeCount: 5,
		GeneratedAt: "2026-09-13", ExcludedL1: []string{"花卉"}})
	require.NoError(t, err)

	src := string(out)
	require.Contains(t, src, "// Code generated by cmd/category-alias-gen. DO NOT EDIT.")
	require.Contains(t, src, "test-model")
	require.Contains(t, src, "花卉")
	require.Contains(t, src, `"捲心菜": "甘藍", // 蔬菜 / id=117`)

	require.Less(t, strings.Index(src, `"捲心菜"`), strings.Index(src, `"牛蒡根"`),
		"要排序輸出，否則每次重跑都產生無意義的 diff")

	_, err = parser.ParseFile(token.NewFileSet(), "category_alias_gen.go", out, parser.AllErrors)
	require.NoError(t, err, "產出必須是合法的 Go 原始碼")
}

func TestRenderSnapshot_RoundTripsThroughLoader(t *testing.T) {
	tr := tree{All: []node{
		{ID: "1", Name: "蔬菜", Level: 1},
		{ID: "117", Name: "甘藍", Level: 2},
		{ID: "311", Name: "初秋", Level: 3},
	}}

	out, err := renderSnapshot(tr)
	require.NoError(t, err)

	snap, err := cache.LoadTreeSnapshot(out)
	require.NoError(t, err)
	require.Len(t, snap.Nodes, 3)
	require.Equal(t, "117", snap.L2ByName()["甘藍"].ID)
	require.True(t, snap.NodeNames()["初秋"])
}
