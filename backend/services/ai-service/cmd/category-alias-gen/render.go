package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

type renderMeta struct {
	Model       string
	Samples     int
	MinAgree    int
	L2Count     int
	NodeCount   int
	GeneratedAt string
	ExcludedL1  []string
}

// renderAliasFile 產生 internal/cache/category_alias_gen.go。排序輸出是為了讓
// 重跑產生的 diff 只反映內容變化，而不是 map 的隨機迭代順序——那份 diff 是
// 「不逐列人工覆核」之下唯一的審閱單位。
func renderAliasFile(accepted []candidate, meta renderMeta) ([]byte, error) {
	sorted := make([]candidate, len(accepted))
	copy(sorted, accepted)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Alias < sorted[j].Alias })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/category-alias-gen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// 來源：active 分類樹的 %d 個 L2（排除 L1：%s），全樹 %d 個節點，%s\n",
		meta.L2Count, strings.Join(meta.ExcludedL1, "、"), meta.NodeCount, meta.GeneratedAt)
	fmt.Fprintf(&b, "// 模型：%s／samples=%d／minAgree=%d／temperature=0.7\n",
		meta.Model, meta.Samples, meta.MinAgree)
	fmt.Fprintf(&b, "// 重跑：go run ./cmd/category-alias-gen\n\n")
	fmt.Fprintf(&b, "package cache\n\n")
	fmt.Fprintf(&b, "// generatedCategoryAliases 是消費者慣用名 → 分類樹 L2 正式名的生成對照表。\n")
	fmt.Fprintf(&b, "// 修正錯誤的別名請改 synonyms（人工覆寫層），不要手改本檔。\n")
	fmt.Fprintf(&b, "var generatedCategoryAliases = map[string]string{\n")
	for _, c := range sorted {
		fmt.Fprintf(&b, "\t%q: %q, // %s / id=%s\n", c.Alias, c.Target.Name, c.Target.L1Name, c.Target.ID)
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}

// renderSnapshot 寫出 PR gate 要對照的那份樹。含所有層級與所有 L1。
func renderSnapshot(t tree) ([]byte, error) {
	type snapNode struct {
		ID    string `json:"id"`
		Name  string `json:"name"`
		Level int    `json:"level"`
	}
	nodes := make([]snapNode, 0, len(t.All))
	for _, n := range t.All {
		nodes = append(nodes, snapNode{ID: n.ID, Name: n.Name, Level: n.Level})
	}
	sort.Slice(nodes, func(i, j int) bool {
		if nodes[i].Level != nodes[j].Level {
			return nodes[i].Level < nodes[j].Level
		}
		return nodes[i].ID < nodes[j].ID
	})
	return json.MarshalIndent(struct {
		Nodes []snapNode `json:"nodes"`
	}{nodes}, "", " ")
}
