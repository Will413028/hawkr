export const BANK_CODE_OPTIONS: Array<{
	value: string;
	label: string;
	description: string;
}> = BANK_INSTITUTIONS.map((bank) => ({
	value: bank.code,
	label: `${bank.code} · ${bank.name}`,
	description: bank.category,
}));

export const BANK_NAME_ALIASES = Object.fromEntries(
	BANK_INSTITUTIONS.flatMap((bank) => [
		[bank.name, bank.name],
		...(bank.aliases ?? []).map((alias) => [alias, bank.name] as const),
	]),
) as Record<string, string>;

function normaliseBankInput(value: string | undefined): string {
	return (value ?? "")
		.trim()
		.replace(/^0*(\d{3})\s*[·・.、-]?\s*/, "$1 ")
		.replaceAll("臺", "台");
}

export function findBankInstitution(
	value: string | undefined,
): BankInstitution | undefined {
	const input = normaliseBankInput(value);
	if (!input) return undefined;
	const codeMatch = input.match(/^(\d{3})\b/);
	if (codeMatch) {
		const byCode = BANK_INSTITUTIONS.find((bank) => bank.code === codeMatch[1]);
		if (byCode) return byCode;
	}
	return BANK_INSTITUTIONS.find((bank) => {
		const names = [bank.name, ...(bank.aliases ?? [])].map(normaliseBankInput);
		return names.some((name) => input === name || input.includes(name));
	});
}

export function normaliseBankName(value: string | undefined): string {
	const bank = findBankInstitution(value);
	if (bank) return bank.name;
	return (value ?? "").trim();
}

export function getBankCodeForValue(value: string | undefined): string {
	return findBankInstitution(value)?.code ?? "";
}

export function getBankOptionsForValue(
	code: string | undefined,
	name?: string | undefined,
) {
	const current = findBankInstitution(code || name);
	const options = [...BANK_CODE_OPTIONS];
	if (!current && name?.trim()) {
		options.unshift({
			value: name.trim(),
			label: name.trim(),
			description: "自訂金融機構",
		});
	}
	return options;
}
