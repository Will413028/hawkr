export type TaiwanCity = keyof typeof TAIWAN_CITIES;

export const TAIWAN_CITY_OPTIONS = Object.keys(TAIWAN_CITIES);

export function getDistrictOptions(city: string | undefined): string[] {
	if (!city) return [];
	return [...(TAIWAN_CITIES[city as TaiwanCity] ?? [])];
}

/**
 * 內政部與 TGOS 寫「臺」、物流名稱表寫「台」：縣市與區名稱轉成名稱表的寫法（整個字串，
 * 如台西鄉、霧台鄉、台東市）。物流功能的臺／台比對與轉換都經這一個函式。
 */
export function toLogisticsName(name: string | undefined): string {
	return (name ?? "").trim().replaceAll("臺", "台");
}

export function getKnownCity(city: string | undefined): string {
	const normalised = toLogisticsName(city);
	return (
		TAIWAN_CITY_OPTIONS.find(
			(option) => toLogisticsName(option) === normalised,
		) ?? ""
	);
}

export function getKnownDistrict(
	city: string | undefined,
	district: string | undefined,
): string {
	const value = (district ?? "").trim();
	if (!value) return "";
	return getDistrictOptions(city).includes(value) ? value : "";
}

