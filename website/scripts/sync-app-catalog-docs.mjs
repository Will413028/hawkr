#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appsRoot = resolve(process.env.HAWKR_APPS_ROOT || resolve(webRoot, ".."));
for (const app of ["buyer", "seller"]) {
	const name = app === "buyer" ? "Buyer" : "Seller";
	const source = readFileSync(
		resolve(appsRoot, `${app}-app/docs/component-library.md`),
		"utf8",
	);
	const expected = `import { Meta } from "@storybook/addon-docs/blocks";\n\n<Meta title="Apps/${name} API" />\n\n{/* Generated by scripts/sync-app-catalog-docs.mjs. Edit the App document. */}\n\n${source}`;
	const destination = resolve(webRoot, `stories/apps/${name}Api.mdx`);
	if (process.argv.includes("--check")) {
		if (readFileSync(destination, "utf8") !== expected)
			throw new Error(
				`${name} API docs drifted; run pnpm storybook:sync-app-docs.`,
			);
	} else writeFileSync(destination, expected);
}
console.log("Buyer and seller catalog API docs are synchronized.");
