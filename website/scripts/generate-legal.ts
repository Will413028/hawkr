#!/usr/bin/env node

/**
 * 賣家入駐文件的產生器。來源只有 docs/legal/ 的三份 Markdown 正本與 seller-agreements.json（manifest）；
 * 版本是正本版本行的生效日，沒有正本的文件（PAYUNI_TERMS）的版本寫在 manifest。輸出：
 *   - features/legal/documents/<正本檔名>.gen.ts：正本的 TS 投影（頁面渲染用）
 *   - features/legal/documents/sellerAgreements.gen.ts：kind → { version, url }（web 送出同意用）
 *   - backend/internal/modules/seller/internal/model/agreement_gen.go：CurrentAgreements
 * 在 website/ 執行 `pnpm gen:legal`；`--check` 只比對、不寫檔。
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseLegalMarkdown } from "./legal-markdown";

const KINDS = [
	"SELLER_TERMS",
	"KYC_PRIVACY_NOTICE",
	"PAYUNI_TERMS",
	"FOOD_REGISTRATION_NOTICE",
] as const;
type Kind = (typeof KINDS)[number];

interface ManifestEntry {
	kind: Kind;
	url: string;
	doc?: string;
	version?: string;
}

const GENERATOR = "website/scripts/generate-legal.ts";
const GO_OUT =
	"backend/internal/modules/seller/internal/model/agreement_gen.go";
const TS_DIR = "website/features/legal/documents";

function camelCase(fileBase: string): string {
	return fileBase.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}

function tsValue(value: unknown, depth = 0): string {
	const pad = "\t".repeat(depth + 1);
	const end = "\t".repeat(depth);
	if (typeof value === "string") return JSON.stringify(value);
	if (Array.isArray(value)) {
		if (value.length === 0) return "[]";
		return `[\n${value.map((v) => `${pad}${tsValue(v, depth + 1)},`).join("\n")}\n${end}]`;
	}
	const entries = Object.entries(value as Record<string, unknown>);
	return `{\n${entries
		.map(([k, v]) => `${pad}${k}: ${tsValue(v, depth + 1)},`)
		.join("\n")}\n${end}}`;
}

function readManifest(root: string): ManifestEntry[] {
	const raw = JSON.parse(
		readFileSync(
			join(root, "website/docs/legal/seller-agreements.json"),
			"utf8",
		),
	) as { agreements: ManifestEntry[] };
	const seen = new Set<string>();
	for (const entry of raw.agreements) {
		if (!KINDS.includes(entry.kind))
			throw new Error(`未知的種類：${entry.kind}`);
		if (seen.has(entry.kind)) throw new Error(`種類重複：${entry.kind}`);
		seen.add(entry.kind);
		if (!entry.url.startsWith("/") && !entry.url.startsWith("https://")) {
			throw new Error(`${entry.kind} 的 url 必須是站內路徑或 https 網址`);
		}
		if (Boolean(entry.doc) === Boolean(entry.version)) {
			throw new Error(
				`${entry.kind} 要嘛有 doc、要嘛有 version，不能兩者都有或都沒有`,
			);
		}
	}
	for (const kind of KINDS) {
		if (!seen.has(kind)) throw new Error(`manifest 缺少 ${kind}`);
	}
	return raw.agreements;
}

/** 回傳「相對於 repo 根目錄的路徑 → 檔案內容」。 */
export function buildOutputs(root: string): Map<string, string> {
	const out = new Map<string, string>();
	const versions = new Map<Kind, { version: string; url: string }>();

	for (const entry of readManifest(root)) {
		if (!entry.doc) {
			versions.set(entry.kind, {
				version: entry.version as string,
				url: entry.url,
			});
			continue;
		}
		const docPath = `website/docs/legal/${entry.doc}`;
		const parsed = parseLegalMarkdown(
			readFileSync(join(root, docPath), "utf8"),
		);
		versions.set(entry.kind, { version: parsed.version, url: entry.url });
		const doc = {
			title: parsed.title,
			version: parsed.version,
			versionLine: parsed.versionLine,
			blocks: parsed.blocks,
		};
		const base = camelCase(entry.doc.replace(/\.md$/, ""));
		out.set(
			`${TS_DIR}/${base}.gen.ts`,
			`// Code generated by ${GENERATOR} from ${docPath}. DO NOT EDIT.\n\nimport type { LegalDocument } from "./legalDocument";\n\nexport const ${entry.kind}: LegalDocument = ${tsValue(doc)};\n`,
		);
	}

	const agreements = Object.fromEntries(KINDS.map((k) => [k, versions.get(k)]));
	out.set(
		`${TS_DIR}/sellerAgreements.gen.ts`,
		`// Code generated by ${GENERATOR} from website/docs/legal. DO NOT EDIT.\n\nexport const SELLER_AGREEMENTS = ${tsValue(agreements)} as const;\n`,
	);

	const goEntries = KINDS.map((k) => {
		const a = versions.get(k) as { version: string; url: string };
		return `\t"${k}": {\n\t\tVersion: ${JSON.stringify(a.version)},\n\t\tURL:     ${JSON.stringify(a.url)},\n\t},\n`;
	}).join("");
	out.set(
		GO_OUT,
		`// Code generated by ${GENERATOR} from website/docs/legal. DO NOT EDIT.\n\npackage model\n\n// CurrentAgreements 是各種文件的現行版本與位置：版本是正本的生效日，網址是 manifest 的 url。\nvar CurrentAgreements = map[AgreementKind]Agreement{\n${goEntries}}\n`,
	);
	return out;
}

function repoRoot(): string {
	return resolve(dirname(fileURLToPath(import.meta.url)), "../..");
}

function main() {
	const root = repoRoot();
	const check = process.argv.includes("--check");
	let drift = 0;
	for (const [rel, content] of buildOutputs(root)) {
		const abs = join(root, rel);
		const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
		if (current === content) continue;
		if (check) {
			console.error(`生成物與來源不同步：${rel}`);
			drift += 1;
			continue;
		}
		mkdirSync(dirname(abs), { recursive: true });
		writeFileSync(abs, content);
		console.log(`wrote ${rel}`);
	}
	if (drift > 0) process.exit(1);
}

if (
	process.argv[1] &&
	resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	main();
}
